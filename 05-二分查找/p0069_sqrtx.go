// LeetCode 第69题 - x 的平方根 (Sqrt(x))
//
// 【难度】简单 | 【面试频率】★★★★ | 【标签】数学、二分查找
//
// 【题目描述】
// 给你一个非负整数 x，计算并返回 x 的算术平方根的整数部分。
// 注意：不允许使用任何内置指数函数和算符。
//
// 【示例 1】
// 输入：x = 4
// 输出：2
//
// 【示例 2】
// 输入：x = 8
// 输出：2
// 解释：8 的算术平方根是 2.82842...，由于返回类型是整数，小数部分将被舍去。
//
// 【数据范围】
// 0 <= x <= 2^31 - 1
//
// 【思路提示】二分找最大的 mid 使 mid*mid <= x，防溢出用 mid <= x/mid 判断。
//
// 题目链接：https://leetcode.cn/problems/sqrtx/
package main

import "fmt"

// mySqrt 返回 x 的整数平方根。
func mySqrt(x int) int {
	left, right := 0, x

	for left <= right {
		mid := left + (right-left)/2
		tmp1 := mid * mid
		if tmp1 == x {
			return mid
		}

		if tmp1 < x {
			tmp2 := (mid + 1) * (mid + 1) // ✅ 存了 tmp2...
			if tmp2 == x {
				return mid + 1
			}

			if (mid+1)*(mid+1) > x { // 🟡 ...但这两行又重新计算了 (mid+1)*(mid+1)，
				return mid //    应该直接用 tmp2 比较
			}

			if (mid+1)*(mid+1) < x { // 🟡 同上，重复计算第三次
				left = mid + 1
			}
		}

		if tmp1 > x {
			right = mid - 1
		}
	}

	return 0 // 🟡 死代码：所有路径都会在循环内 return，这行只为满足编译器
}

// 【V0 点评】
// 编译通过，逻辑完全正确！main 的 5 个用例 + 边界（x=1,2,3,2147395600=46340², 2^31-1）全部通过：
//   ✅ 循环不变量保持得好：tmp2 < x 才 left=mid+1（答案 ≥ mid+1），tmp1 > x 才 right=mid-1（答案 ≤ mid-1）
//   ✅ tmp2 == x 时 return mid+1（完全平方数的处理）正确
//   ✅ 单元素区间收缩到答案时必命中 tmp2 > x 分支，不会误走到 return 0
//   ✅ mid = left + (right-left)/2 防溢出写法正确
//   ✅ 时间 O(log x)，符合题目要求
//   🟡 (mid+1)*(mid+1) 计算了 3 次：tmp2 存了但只在第一个 if 用，后两个 if 又重算，应复用 tmp2
//   🟡 三个子分支结构冗余：本质是"找最后一个 mid 使 mid² <= x"，用 ans 记录法两分支就够（见 V1）
//   🟡 return 0 是死代码（语法必需，永不执行）
//   🟡 溢出说明：Go 64 位平台 int 是 64 位，mid*mid 最大约 2^60 不会溢出；
//      但 32 位平台 mid*mid 会溢出，思路提示的 mid <= x/mid 是防御写法（注意 x=0 时会除零，需特判）
//   🟡 测试建议补充：x=1、x=2147395600（46340²）、x=2^31-1 三个边界

// mySqrtV1 【LeetCode 标准答案】二分查找（ans 记录法），时间 O(log x)，空间 O(1)
func mySqrtV1(x int) int {
	left, right := 0, x
	ans := 0
	for left <= right {
		mid := left + (right-left)/2
		if mid*mid <= x {
			ans = mid      // ✅ mid 可行，记录候选答案
			left = mid + 1 // ✅ 尝试更大的 mid
		} else {
			right = mid - 1 // ✅ mid 太大，收缩右边界
		}
	}
	return ans
}

// 【V1 点评 - LeetCode 标准答案】
// ✅ "找最后一个满足 mid² <= x 的 mid"：只判断收缩方向，不判断邻居 (mid+1)²
// ✅ 只有两个分支，无子分支嵌套，无重复计算
// ✅ 循环自然结束（left > right）返回 ans，没有死代码
// ✅ x=0 无需特判：mid=0, 0<=0 → ans=0, left=1 → 退出返回 0
// ✅ 时间 O(log x)，空间 O(1)
// 与 p0034/p0035 的 lower_bound 模板同源："找边界"类二分都可用 ans 记录法两分支解决
//
// ──────────────────────────────────────────────────────────
// 【深入理解：为什么 ans 记录法找到候选后不提前返回？】
//
// 因为这题找的不是"一个满足 mid² <= x 的 mid"，而是"最后一个满足的 mid"。
// mid 满足条件 ≠ mid 是边界！必须把它右边的空间全部排除，才能确认它是"最后一个"。
//
// 追踪 x=9（答案 3），如果"找到就提前返回"会怎样：
//   left=0,right=9,mid=4: 16 > 9 → right=3
//   left=0,right=3,mid=1: 1 <= 9 → 找到候选！但 1 不是答案 ❌（提前返回就错了）
//   left=2,right=3,mid=2: 4 <= 9 → 又找到候选！但 2 还不是答案 ❌
//   left=3,right=3,mid=3: 9 <= 9 → ans=3, left=4
//   left > right → 返回 3 ✅
//
// ans 记录法的循环不变量：
//   任意时刻：
//     ans   = 目前见过的最大可行 mid
//     [left, right] = 还没探索的、可能存在更大可行 mid 的区域
//   循环结束（left > right）→ 右边再无可能 → ans 就是答案
//
// 循环的职责不是"找到就停"，而是排除法：把 mid 右边的空间搜完，确认没有更大可行解。
//
// 什么情况可以提前返回？
//   只有 mid*mid == x（精确命中）时可以立刻 return mid——
//   此时 mid 右边所有数的平方必然 > x，不可能有更大的可行解：
//     if mid*mid == x { return mid }
//   这样写也正确，但只省掉最后几轮迭代（总共才 ~31 轮），标准模板为简洁通常不加。
//
// 与 V0（邻居判断法）的本质对比：
//   |                | V0 邻居判断          | V1 ans 记录            |
//   |----------------|----------------------|------------------------|
//   | 提前返回       | ✅ 检查 (mid+1)² 确认 | ❌ 排空右边才确认       |
//   | 分支数         | 5 个                 | 2 个                   |
//   | 出错风险       | 高（邻居检查要处理    | 低（只判收缩方向，      |
//   |                | 边界，p0034/35 的 bug | 天然无边界特判）        |
//   |                | 都源于此）           |                        |
//
// 本质：V0 用"偷看邻居"提前确认边界（快但容易踩坑），
//      V1 用"排除整个右半区"确认边界（多跑几轮但绝对稳）。
//      二分总共只有几十轮，多跑几轮的代价远小于写错边界条件的风险。
// ──────────────────────────────────────────────────────────

// mySqrtV2 牛顿迭代法，时间 O(log x)，空间 O(1)——面试加分项
func mySqrtV2(x int) int {
	if x == 0 {
		return 0 // 特判：避免下方 x/r 除零
	}
	r := x
	for r*r > x {
		r = (r + x/r) / 2 // 牛顿迭代：r ← (r + x/r) / 2，向 sqrt(x) 收敛
	}
	return r
}

// 【V2 点评 - 牛顿迭代法】
// ✅ 数学背景：求 f(r) = r² - x = 0 的根，切线迭代 r ← r - f(r)/f'(r) = (r + x/r)/2
// ✅ 整数版从 r=x 出发单调递减，恰好停在 floor(sqrt(x))，不会跳过
// ✅ 收敛极快（二次收敛），实际迭代次数少于二分
// ⚠️ x=0 必须特判（x/r 除零）；r*r 在 64 位平台安全
// 面试中提一句牛顿迭代是很好的加分项

// ──────────────────────────────────────────────────────────
// 【LeetCode 解法对比】
//
// | 解法                       | 时间     | 空间   | 面试期望      |
// |----------------------------|----------|--------|---------------|
// | 邻居判断二分（V0）          | O(log x) | O(1)   | ⚠️ 正确但冗余 |
// | 二分 ans 记录（V1 标准答案）| O(log x) | O(1)   | ✅ 面试首选   |
// | 牛顿迭代（V2）              | O(log x) | O(1)   | ✅ 加分项     |
//
// 【核心易错点】
// 1. 32 位平台 mid*mid 溢出：mid 最大约 46341，mid² ≈ 2.1×10^9 超过 int32；
//    防御写法用 mid <= x/mid 等价判断，但 x=0 时除零需特判
//    （Go 主流平台 int 是 64 位，mid*mid 最大约 2^60，安全）
// 2. 完全平方数：x=4 返回 2 而不是 1——"找最后一个 mid² <= x"天然覆盖
// 3. x=0 和 x=1 的边界：返回自身，别返回 0/1 弄反
// 4. 二分的本质是"找边界"：ans 记录法（满足条件就记录并右移）比邻居判断法简洁可靠
//
// 【面试讲解建议】
// 1. 先说思路："二分找最后一个 mid 使 mid² <= x，ans 记录可行解"
// 2. 提到溢出："64 位平台安全；32 位用 mid <= x/mid 但要防除零"
// 3. 加分项：牛顿迭代 r ← (r + x/r)/2，二次收敛
// 4. 分析复杂度：时间 O(log x)，空间 O(1)
// ──────────────────────────────────────────────────────────

func main() {
	fmt.Println(mySqrt(0)) // 0
	fmt.Println(mySqrt(4)) // 2
	fmt.Println(mySqrt(8)) // 2
	fmt.Println(mySqrt(9)) // 3
	fmt.Println(mySqrt(10)) // 3

	// V0/V1/V2 结果一致（V0 本题正确，只是写法冗余）
	fmt.Println(mySqrt(1), mySqrtV1(1), mySqrtV2(1))                           // 1 1 1
	fmt.Println(mySqrt(2147395600), mySqrtV1(2147395600), mySqrtV2(2147395600)) // 46340（46340² 恰好是完全平方数）
	fmt.Println(mySqrtV1(2147483647), mySqrtV2(2147483647))                     // 46340（2^31-1 边界）
}
