// LeetCode 第50题 - Pow(x, n) (Pow(x, n))
//
// 【难度】中等 | 【面试频率】★★★★ | 【标签】递归、数学、二分思想（快速幂）
//
// 【题目描述】
// 实现 pow(x, n)，即计算 x 的整数 n 次幂函数（即 x^n）。
//
// 【示例 1】
// 输入：x = 2.00000, n = 10
// 输出：1024.00000
//
// 【示例 2】
// 输入：x = 2.10000, n = 3
// 输出：9.26100
//
// 【示例 3】
// 输入：x = 2.00000, n = -2
// 输出：0.25000
// 解释：2^-2 = 1/2^2 = 1/4 = 0.25
//
// 【数据范围】
// -100.0 < x < 100.0
// -2^31 <= n <= 2^31-1
// n 是一个整数
// 要么 x 不等于 0，要么 n > 0
// -10^4 <= x^n <= 10^4
//
// 【思路提示】快速幂：x^n = (x^(n/2))^2，n 为奇数时多乘一次 x；
// 注意 n = -2^31 取反会溢出，先把 n 转成 int64 或用"除以 2"的方式处理。
//
// 题目链接：https://leetcode.cn/problems/powx-n/
package main

import "fmt"

// myPow 快速幂计算 x 的 n 次方。
func myPow(x float64, n int) float64 {
	if n == 0 {
		return 1
	}

	var nagtive bool = false // 🟡 拼写错误：nagtive → negative
	if n < 0 {
		nagtive = true
		n = -n // 🟡 32 位平台上 n = -2^31 取反会溢出回负数（64 位平台 int 为 64 位，恰好安全）
	}

	var result float64 = 1
	for n > 0 { // 🔴 O(n) 暴力循环：n 最大 2^31-1（约 21 亿次乘法），LeetCode 会超时
		result *= x //    题目要求 O(log n) 的快速幂（见文件头思路提示）
		n--
	}

	if nagtive {
		result = 1 / result
	}

	return result
}

// 【V0 点评】
// 编译通过，小 n 结果正确，但算法不达标：
//   🔴 时间复杂度 O(n)：逐次相乘，n 最大 2^31-1 时约 21 亿次循环，LeetCode 超时（TLE）
//      题目和思路提示都要求快速幂：x^n = (x^(n/2))^2，奇数时多乘一个 x，O(log n)
//   🟡 拼写错误：nagtive 应为 negative
//   🟡 n = -n 在 32 位平台对 n = -2^31 会溢出（取反后仍是负数，循环不执行，返回 1）
//      64 位平台 int 是 64 位恰好没事；标准做法是转 int64 或像 V1 一样用 1/x 转正幂
//   🟡 main 只测了小 n，测不出超时问题（n=10^9 时 V0 需要数秒，V1 瞬间完成）
//   ✅ n == 0 返回 1 正确
//   ✅ 负指数取倒数（1/result）的处理正确
//   ✅ O(n) 版本的边界（n 正负、零）都处理对了——思路对，只是复杂度不够

// myPowV1 【LeetCode 标准答案】快速幂（迭代版），时间 O(log n)，空间 O(1)
func myPowV1(x float64, n int) float64 {
	if n < 0 {
		x = 1 / x // ✅ 负指数：先取倒数，把问题统一成正指数
		n = -n    // 64 位平台 int 为 64 位，n = -2^31 取反安全
	}

	result := 1.0
	for n > 0 {
		if n&1 == 1 { // ✅ n 的二进制最低位是 1，把当前的 x 乘进结果
			result *= x
		}
		x *= x // ✅ x 自身平方：x, x^2, x^4, x^8, ...（只需 log n 次平方）
		n >>= 1
	}
	return result
}

// 【V1 点评 - LeetCode 标准答案】
// ✅ 快速幂（二进制拆解）：把 n 看成二进制，每一位对应 x 的 2^k 次幂
//    例如 n=10=1010b：x^10 = x^8 * x^2，只需 4 次平方 + 1 次乘法，而非 10 次乘法
// ✅ 时间 O(log n)：n = 2^31-1 也只需 31 次循环；空间 O(1)
// ✅ 负指数先取倒数（x = 1/x; n = -n），避免最后除法，也天然规避 1/0 风险
// ✅ 迭代写法无递归栈开销，是面试首选
// 追踪 myPowV1(2.0, 10)：n=1010b
//   n=10: bit=0, x→4,   n→5
//   n=5:  bit=1, result=4, x→16,  n→2
//   n=2:  bit=0, x→256, n→1
//   n=1:  bit=1, result=4*256=1024 → 返回 1024 ✅

// myPowV2 快速幂（递归版），时间 O(log n)，空间 O(log n)——便于理解分治思想
func myPowV2(x float64, n int) float64 {
	if n < 0 {
		return 1 / myPowV2(x, -n) // ✅ 负指数：转化为正指数的倒数
	}
	if n == 0 {
		return 1
	}
	half := myPowV2(x, n/2) // 先算 x^(n/2)
	if n%2 == 0 {
		return half * half // 偶数：x^n = (x^(n/2))^2
	}
	return half * half * x // 奇数：再多乘一个 x
}

// 【V2 点评 - 递归版快速幂】
// ✅ 分治思想直观：x^n = (x^(n/2))^2，奇数补乘 x
// ✅ 时间 O(log n)，空间 O(log n)（递归栈）
// ⚠️ 面试可用，但迭代版（V1）更优：无栈开销，且不用处理 -n 溢出边界

// ──────────────────────────────────────────────────────────
// 【LeetCode 解法对比】
//
// | 解法                        | 时间     | 空间      | 面试期望        |
// |-----------------------------|----------|-----------|-----------------|
// | 暴力循环（V0）               | O(n)     | O(1)      | ❌ 大 n 超时    |
// | 快速幂迭代（V1 标准答案）    | O(log n) | O(1)      | ✅ 面试首选     |
// | 快速幂递归（V2）             | O(log n) | O(log n)  | ⚠️ 可以         |
//
// 【核心易错点】
// 1. O(n) 循环在 n = 2^31-1 时约 21 亿次乘法，必然超时——本题考点就是快速幂
// 2. n = -2^31 取反溢出：64 位平台没事，32 位平台 -n 仍是负数；
//    标准做法：转 int64，或像 V1 先 x = 1/x 再取正
// 3. 负指数处理：1/myPow(x, -n) 或先取倒数，两种都行
// 4. 奇数指数要补乘一次 x：half*half*x，别丢
//
// 【面试讲解建议】
// 1. 先说思路："快速幂，把 n 拆成二进制，每一位对应 x 的 2^k 次幂"
// 2. 举例说明：x^10 = x^8 * x^2（10 = 1010b）
// 3. 写迭代版：n&1 判断最低位，x *= x 平方，n >>= 1 右移
// 4. 提到负指数和 -2^31 溢出边界，展示严谨性
// ──────────────────────────────────────────────────────────

func main() {
	fmt.Println(myPow(2.0, 10))  // 1024
	fmt.Println(myPow(2.1, 3))   // 9.261
	fmt.Println(myPow(2.0, -2))  // 0.25

	// V1/V2 与 V0 结果一致，但 V0 在大 n 下超时
	fmt.Println(myPowV1(2.0, 10), myPowV2(2.0, 10))  // 1024 1024
	fmt.Println(myPowV1(2.0, -2), myPowV2(2.0, -2))  // 0.25 0.25
	fmt.Println(myPowV1(1.0001, 100000))             // ≈1.05（V0 同样输入需要 10 万次循环）
	fmt.Println(myPowV1(2.0, -2147483648))           // 0（n = -2^31 边界，V1 正常）
}
