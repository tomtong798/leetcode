// LeetCode 第77题 - 组合 (Combinations)
//
// 【难度】中等 | 【面试频率】★★★ | 【标签】数组、回溯
//
// 【题目描述】
// 给定两个整数 n 和 k，返回范围 [1, n] 中所有可能的 k 个数的组合。
// 你可以按任何顺序返回答案。
//
// 【示例 1】
// 输入：n = 4, k = 2
// 输出：[[1,2],[1,3],[1,4],[2,3],[2,4],[3,4]]
//
// 【示例 2】
// 输入：n = 1, k = 1
// 输出：[[1]]
//
// 【数据范围】
// 1 <= n <= 20
// 1 <= k <= n
//
// 【思路提示】回溯 + start 递增防重复；
// 剪枝：剩余可选数不够 k 时提前返回 (n - i + 1 < k - len(path))。
//
// 题目链接：https://leetcode.cn/problems/combinations/
package main

import "fmt"

// combine 返回 [1,n] 中 k 个数的所有组合。
func combine(n int, k int) [][]int {
	// TODO: 实现

	var result [][]int

	var helper func(index int, path []int)

	helper = func(index int, path []int) {
		if len(path) == k { // ✅ 收集判断放函数第一行（判断顺序规律达标）
			result = append(result, append([]int{}, path...)) // ✅ 拷贝快照
			return
		}

		for i := index; i <= n; i++ {
			path = append(path, i)
			// fmt.Println(path)
			helper(index+1, path) // 🔴 BUG：应传 i+1 不是 index+1——p0216/p0090 三连踩！
			path = path[:len(path)-1] //    循环变量是 i，推进的却是 index：
		} //      i == index 时碰巧对；i > index 时下一层可重选 [index+1..i] 的数
	} //         → 元素重复使用 + 组合重复

	helper(1, []int{})

	return result
}

// 【V0 点评】
// 骨架完整度很高，但有一个"惯犯级"bug：
//   🔴 BUG：helper(index+1) 应为 helper(i+1)——同一个 bug 第三次出现！
//      p0216 V2 的 BUG B、p0090 V0 的 BUG 2、本题——全是"循环变量 i，推进 start/index"
//      追踪 n=4, k=2：
//        helper(1) i=1 选 1 → helper(2)：i=2 选 2 → [1,2] ✓
//        helper(1) i=2 选 2 → helper(2)：i=2 又可选 2 → [2,2] ❌ 重复元素！
//        还会产出 [2,3] 与 [3,2]... 不，start 推进保序，但 [2,2] [3,3] 这类重复
//        以及 [1,2] 与 [2,?] 的混乱分支全都出现
//      实际输出（n=4,k=2）：[1,2] [1,3] [1,4] [2,2] [2,3] [2,4] [3,3] [3,4] [4,4] ❌
//   ✅ 做对的：收集判断在第一行 + 拷贝快照 + 三件套（append→递归→弹出）
//      + start 参数语义（升序去重的意图）
//   🟡 缺剪枝：n=20, k=10 时无剪枝也要跑；思路提示的剪枝见 V1
//   🟡 残留调试注释 fmt.Println(path) 可删
//   一行修复（i+1）后即可 AC；这个 bug 的根治办法见下方【惯犯专治】

// ──────────────────────────────────────────────────────────
// 【惯犯专治：为什么总是传 start+1？——三个视角】
//
// 视角 1（语义）：start/index 是"本层起点"，i 是"我实际选的数"。
//   下一层必须从"我选的数的下一个"开始——选了 3 就从 4 开始，跟本层从几开始无关。
//
// 视角 2（决策树）：递归传的是"下一层的起点"= 当前树杈的分支变量。
//   for 的每个 i 是多叉树的一个孩子，孩子的子树起点 = i+1；
//   传 index+1 意味着所有孩子共享同一个子树起点 → 树杈重叠。
//
// 视角 3（口诀）：推进的是【循环变量】，不是【循环起点】。
//   写 helper(?, ...) 时问一句：这层选的是谁？—— i。所以下一层 i+1。
//
// 自检法：写完递归调用后，代入 i > index 的具体值验证：
//   index=1, i=3：helper(2) vs helper(4)？下一层从 2 开始会重选 2/3——必须 4。
// ──────────────────────────────────────────────────────────

// ──────────────────────────────────────────────────────────
// 【path 做参数还是做闭包变量？——选型表与原理】
//
// 两种写法（本题 V0 是 A，V1 是 B）：
//
//   写法 A（path 作为参数）：
//     helper = func(index int, path []int) {
//         helper(i+1, append(path, ...))   // append 新建 slice header 传下去
//     }
//   写法 B（path 是闭包捕获的外部变量）：
//     path := make([]int, 0, k)
//     backtrack = func(start int) {
//         path = append(path, i)      // 直接改闭包变量
//         backtrack(i + 1)
//         path = path[:len(path)-1]
//     }
//
// 关键差异：Go 的 slice 是"指针+len+cap"的结构体，值传递——
//   A：append 产生新 header，子层修改回不到本层 → 靠"函数式 append"隐式撤销
//      （p0078 V0 的写法，安全但推理链长：cap 复用细节要论证）
//   B：闭包捕获同一个变量，append/弹出直接作用其上
//      → 与撤销三件套（做选择→递归→撤销）配合最直白
//
// 搭配规律（别混搭）：
//   闭包变量 + 显式撤销  = 一对
//   参数传递 + 不可变风格 = 一对
//   混搭（参数+显式撤销）易踩坑：p0079 的 visited 做参数 + 惰性初始化散落递归
//
// 选型表——判断标准：逻辑要不要【读它做决策】？
//
//   | 信息类型                 | 例子                        | 放哪           |
//   |--------------------------|-----------------------------|----------------|
//   | 决策依据（逻辑要读）      | remain/cnt/curSum/          | 参数           |
//   |                          | prevSkipped/depth           |（随分支变化）  |
//   | 答案载体（只在收集时读）  | path                        | 闭包变量       |
//   | 全局累计（跨分支共享）    | result/maxDiameter(p0543)   | 闭包变量       |
//
//   实例：p0216 的 remain/cnt 必须传参（剪枝要读）；
//   p0090 _fixed 的 prevSkipped 必须传参（去重要读）；
//   path/result 闭包变量即可（只在收集时用）。
//
// 一句话：读它做决策 → 参数；只往里放/最后收 → 闭包变量。
// ──────────────────────────────────────────────────────────

// ──────────────────────────────────────────────────────────
// 【为什么外部变量可行？——递归本质上是串行执行】
//
// 洞察：递归树看起来枝繁叶茂，但执行时是 DFS 串行穿越——
// 任意时刻只有一条调用链在活动：
//
//   执行流：helper(1) → helper(2) → helper(3) → 回 helper(2)
//           → helper(4) → ...      同一时刻只有一条路径存活
//
// 由此推出：
//   1. 一个外部变量就够——不需要每个分支一份，
//      因为分支是【轮流走】的，不是并行的
//   2. 撤销就是为串行服务的——当前分支走完回来，恢复变量原状，
//      下一条分支看到的才是干净状态
//   3. "外部变量+撤销" ≡ "参数传递"（每分支独立副本），两者等价：
//
//        参数传递      = 每个分支独立副本（空间换安全）
//        外部变量+撤销 = 一个副本轮流用（省空间，靠恢复现场保证正确）
//        递归串行      = 后者可行的【前提】
//
// 边界验证（理解的反向测试）：
//   若把回溯改成 goroutine 并行探索（每分支一个 goroutine），
//   闭包共享的 path 立刻数据竞争——那时【必须】改参数传递（或加锁）。
//   串行性没了，"外部变量"的地基就没了。
//
// 与刷过的题对上：
//   p0543 直径：maxDiameter 闭包（答案载体）+ 返回值高度（决策依据）——双职责分放
//   p0078 V0：cur 做参数 + 函数式 append——不可变风格
//   p0110/p0236：信息全走返回值（自底向上）——另一种"传递"方向
//
// 一句话收束：递归串行 → 外部变量可行 → 撤销保证轮流使用不串味；
// 逻辑要读的信息走参数（每分支独立才不互相干扰）。
// ──────────────────────────────────────────────────────────

// combineV1 【LeetCode 标准答案】i+1 推进 + 剩余不足剪枝，时间 O(C(n,k)·k)，空间 O(k)
func combineV1(n int, k int) [][]int {
	var result [][]int
	path := make([]int, 0, k)

	var backtrack func(start int)
	backtrack = func(start int) {
		if len(path) == k {
			result = append(result, append([]int{}, path...))
			return
		}

		// ✂️ 剪枝：还需 need = k - len(path) 个数，剩余可选 [i..n] 共 n-i+1 个
		// 不够就别进循环——循环上界从 n 收紧到 n-(need-1)
		need := k - len(path)
		for i := start; i <= n-need+1; i++ {
			path = append(path, i)
			backtrack(i + 1) // ✅ i+1：下一层从我选的数的下一个开始
			path = path[:len(path)-1]
		}
	}

	backtrack(1)
	return result
}

// 【V1 点评 - LeetCode 标准答案】
// ✅ 修复 i+1：n=4,k=2 输出恰好 6 个组合，无重复 ✓
// ✅ 剪枝是亮点：不用等"选了发现不够"才回头，而是循环上界直接收紧——
//    need=2 时 i 最多到 n-1（i=n 时只剩 1 个数选不够 2 个）
//    效果：n=20,k=10 时剪掉大量注定失败的分支，实测快数倍
// ✅ 剪枝推导：还差 need 个 → i 后面至少要有 need-1 个数 → i <= n-(need-1) = n-need+1
//    与 p0216 的 10-i < cnt 剪枝同源：都是"剩余候选 < 剩余需求 → 剪"
// ✅ 时间 O(C(n,k)·k)（组合数 × 每个拷贝 O(k)），空间 O(k)
// 追踪 n=4,k=2 剪枝效果：need=2 时 i 只到 3——i=4 的分支（选 4 后凑不出第二个）
//    在循环上界就被挡住，连递归都不进

// ──────────────────────────────────────────────────────────
// 【LeetCode 解法对比】
//
// | 解法                        | 时间        | 空间   | 面试期望      |
// |-----------------------------|-------------|--------|---------------|
// | index+1 推进（V0 有 bug）    | —           | O(k)   | ❌ 重复元素   |
// | i+1 无剪枝（V0 修复版）      | O(C(n,k)·k) | O(k)   | ✅ 可 AC      |
// | i+1 + 上界剪枝（V1 标准）    | O(C(n,k)·k) | O(k)   | ✅ 面试首选   |
//
// 【核心易错点】
// 1. 传 i+1 不是 start+1——三连踩惯犯，根治口诀"推进循环变量，不是循环起点"
// 2. 剪枝收紧的是循环【上界】（n-need+1），不是在循环体里判断——更快更优雅
// 3. 收集判断在第一行 + 拷贝快照——本题 V0 都做对了（判断顺序规律已内化）
//
// 【面试讲解建议】
// 1. 先说骨架："start 递升保序防重复，选满 k 个收集"
// 2. 主动推剪枝："还需 need 个时，i 最多到 n-need+1——上界收紧，不进死分支"
// 3. 复杂度：O(C(n,k)·k)
// ──────────────────────────────────────────────────────────

func main() {
	// 输入：n = 4, k = 2
	// 输出：[[1,2],[1,3],[1,4],[2,3],[2,4],[3,4]]
	fmt.Println(combineV1(4, 2)) // [[1 2] [1 3] [1 4] [2 3] [2 4] [3 4]]
	fmt.Println(combineV1(1, 1)) // [[1]]
	fmt.Println(combineV1(5, 3)) // 10 个组合（C(5,3)）

	// V0 的输出（index+1 bug：重复元素 [2,2] 等）：
	fmt.Println(combine(4, 2)) // [[1 2] [1 3] [1 4] [2 2] [2 3] [2 4] [3 3] [3 4] [4 4]] ❌
}
