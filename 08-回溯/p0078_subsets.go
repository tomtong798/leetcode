// LeetCode 第78题 - 子集 (Subsets)
//
// 【难度】中等 | 【面试频率】★★★★★ | 【标签】位运算、数组、回溯
//
// 【题目描述】
// 给你一个整数数组 nums，数组中的元素互不相同。返回该数组所有可能的子集（幂集）。
// 解集不能包含重复的子集。你可以按任意顺序返回解集。
//
// 【示例 1】
// 输入：nums = [1,2,3]
// 输出：[[],[1],[1,2],[1,2,3],[1,3],[2],[2,3],[3]]
//
// 【示例 2】
// 输入：nums = [0]
// 输出：[[],[0]]
//
// 【数据范围】
// 1 <= nums.length <= 10
// -10 <= nums[i] <= 10
// nums 中的所有元素互不相同
//
// 【思路提示】回溯：每个节点都算一个子集，进入递归先收集当前路径；
// 用 start 下标保证组合不重复。也可用二进制枚举 2^n 个子集。
//
// 题目链接：https://leetcode.cn/problems/subsets/
package main

import "fmt"

// subsets 返回所有子集。
func subsets(nums []int) [][]int {
	// 依次遍历 nums 中的元素作
	// 每个元素可以选择也可以不选择
	// ✅ 模型认知正确：二叉决策树（选/不选）——p0090 V2 同款模板

	var result [][]int
	// var tmp = []int{}
	// for i := range nums {
	// 	result = append(result, tmp)
	// 	tmp = append(tmp, nums[i])
	// 	result = append(result, tmp)
	// }
	// 🟡 注释掉的旧思路有 bug：append(tmp) 复用底层数组 + result 里的引用共享，
	//    "每加一个元素收集两次"也凑不出幂集（只是前缀链）——删掉为好

	var helper func(index int, cur []int)
	helper = func(index int, cur []int) {
		if index == len(nums) { // ✅ 终止：决策完所有元素
			result = append(result, append([]int{}, cur...)) // ✅ 拷贝收集（p0090 的坑已修）
			return
		}

		helper(index+1, append(cur, nums[index])) // ✅ 选：append 产生新 slice header，
		helper(index+1, cur) // ✅ 不选：传原 cur      //    两个分支互不干扰——
	} //    这是"用函数式 append 替代显式撤销"的写法（见点评分析）

	helper(0, []int{})

	return result
}

// 【V0 点评】
// 完全正确！验证 [1,2,3] 输出 8 个子集、[0] 输出 2 个——一次通过：
//   ✅ 模板 B（二叉决策）骨架标准：无循环、恰好两次递归（选/不选）、index+1 推进
//      ——对比 p0090 V0 的模板混用，这次纯度 100%
//   ✅ 收集拷贝快照：append([]int{}, cur...)——p0090/p0216 的 BUG C 教训已吸收
//   ✅ "不可变风格"的撤销：没有显式的 cur = cur[:len-1]，而是靠
//      helper(index+1, append(cur, ...)) 传新 slice——append 返回新 header，
//      原 cur 不受影响，"不选"分支天然拿到干净状态——等价于撤销，且更函数式
//      ⚠️ 但有个隐藏前提：append 可能在原数组上原地写（cap 足够时）——
//      本题恰好安全的原因：cur 每次 +1 递增，cap 扩容后旧分支的 len 不变，
//      原地写只发生在"已丢弃的前缀区域"。能跑对，但推理链条长；
//      显式撤销（V1）语义更稳，两种都算标准
//   ✅ 时间 O(n·2^n)，空间 O(n) 递归栈
//   🟡 注释掉的旧尝试（tmp 复用版）有引用共享 bug，建议删除避免误导
//   🟡 与 p0090 的联动：本题无重复元素 → 不需要去重；
//      p0090 加了重复元素 → 同样的骨架 + prevSkipped 去重（你的 _fixed 版）
// 无需修改——可直接提交 AC；这是 p0090 系列复盘后的漂亮回归

// subsetsV1 【LeetCode 标准答案】模板 A（start 推进 + 进入即收集），时间 O(n·2^n)，空间 O(n)
func subsetsV1(nums []int) [][]int {
	var result [][]int
	path := make([]int, 0, len(nums))

	var backtrack func(start int)
	backtrack = func(start int) {
		result = append(result, append([]int{}, path...)) // ✅ 每个节点都是解，进入即收集（含空集）

		for i := start; i < len(nums); i++ {
			path = append(path, nums[i]) // 做选择
			backtrack(i + 1)             // 推进 i+1（不是 start+1）
			path = path[:len(path)-1]    // 撤销（显式）
		}
	}

	backtrack(0)
	return result
}

// 【V1 点评 - LeetCode 标准答案（模板 A）】
// ✅ 与 V0 产出相同的 8 个子集，但树形不同：
//    V0（二叉决策）：树深 n，每层分"选/不选"，叶子收集 → 输出顺序按决策序列
//    V1（start 推进）：树分叉 = "下一个选谁"，每节点收集 → 输出按字典序（前缀优先）
// ✅ 显式撤销三件套（append → 递归 → 弹出）——回溯的标准形态，语义最稳
// ✅ "进入即收集"是子集题（模板 A）的关键：树上每个节点都是一个子集
// 两种模板对照与选择，见 p0090 文档的【两种模板对照】——同一知识网络

// subsetsV2 位运算枚举：n 位二进制，第 i 位 =1 表示选 nums[i]，时间 O(n·2^n)，空间 O(1)
func subsetsV2(nums []int) [][]int {
	n := len(nums)
	total := 1 << n // 2^n 个子集
	result := make([][]int, 0, total)

	for mask := 0; mask < total; mask++ { // 枚举 000..111 所有可能
		subset := []int{}
		for i := 0; i < n; i++ {
			if mask&(1<<i) != 0 { // 第 i 位是 1 → 选入
				subset = append(subset, nums[i])
			}
		}
		result = append(result, subset)
	}
	return result
}

// 【V2 点评 - 位运算枚举】
// ✅ 洞察：子集 = 每个元素选/不选 = n 个比特位 → 子集总数 2^n = 位组合总数
// ✅ 迭代无递归：mask 从 0（空集）到 2^n-1（全集），按位拆出子集
// ✅ 空间 O(1)（不含结果）；n≤10 时 2^10=1024，非常快
// 🟡 局限：只适用于"无重复元素"的幂集题（p0090 有重复时位枚举去重麻烦，回溯更好写）
// 🟡 输出顺序与回溯不同（按 mask 数值序）——题目允许任意顺序，无妨
// 面试定位：作为"另一种 O(2^n) 思路"展示广度；核心还是回溯模板

// ──────────────────────────────────────────────────────────
// 【决策树视角：二叉决策 ↔ 二叉树遍历的同构（子集系列收尾）】
//
// 发现：二叉决策回溯的写法很像二叉树遍历——
//   选择与不选择，其实就是二叉树的两个分支：
//
//   二叉决策回溯                        二叉树遍历
//   ─────────────────────             ─────────────────────
//   选 nums[index] → helper(index+1)  dfs(node.Left)
//   不选            → helper(index+1) dfs(node.Right)
//   index 走到头 → 收集              node == nil → 返回
//
// 回溯的递归树，本质是一棵【隐式二叉树】——p0078 的 3 个元素展开
// 就是深度 3 的满二叉树，8 个叶子 = 2^3 个子集：
//
//                        index=0, cur=[]
//                     选1 /         \ 不选1
//                 index=1           index=1
//               [1]选2/ \不选2   选2/  \不选2
//                    ...             ...
//                  8 个叶子（2³），每个叶子 = 一个子集
//
// p0100（相同树）的 same(l,r) = 值等 && same(l.L,r.L) && same(l.R,r.R)
// 与 helper(选)+helper(不选) 是【同一台递归机器】跑两棵不同的树——
// 一棵显式存在内存里，一棵是虚拟的决策空间。
//
// 边界也同构：二叉树的 nil 递归基 = 决策树的"没有更多元素可决策"
// （index == len(nums)）；p0079 网格的越界检查同理（出网格 = 隐式树的 nil）
// 树遍历技巧可搬给回溯：剪枝 = 提前 return 空子树（p0110 的 -1 哨兵 = 剪枝）；
// 前序/后序位置 = 做选择/撤销选择的位置（p0226 的两种范式）；
// 不可变传参免撤销（p0017 字符串）≈ 函数式 append（本题 V0）。
//
// 一句话：回溯 = 在一棵虚拟的决策树上做 DFS。
// ──────────────────────────────────────────────────────────

// ──────────────────────────────────────────────────────────
// 【两棵树的精确形状与选型法】
//
// 模板 B（二叉决策）= 【满二叉树】，树形固定：
//
//                      [1,2,3] index=0
//                     /          \
//               选1                 不选1
//            [1] idx=1            [] idx=1
//            /    \              /    \
//         选2    不选2        选2    不选2
//        [1,2]   [1]         [2]     []
//         /\      /\          /\      /\
//       ...     ...        ...     ...
//       8 个叶子（2³），每个叶子 = 一个子集
//
//   深度永远 n，每节点恰好 2 分支，不管元素是什么；叶子才收集。
//
// 模板 A（start 推进）= 【不规则多叉树】，树形随 start 收缩：
//
//                       []
//               /       |       \      ← 第 1 个选谁：1 / 2 / 3
//             [1]      [2]      [3]
//            /   \      |
//         [1,2] [1,3] [2,3]
//           |
//        [1,2,3]
//
//   每层孩子数 = n - start（候选越来越少）；每个节点都是子集（进入即收集）。
//
// 由树形差异直接推出的三个不同点：
//
//   | 推论       | 二叉决策（满二叉树）        | start 推进（多叉树）       |
//   |------------|-----------------------------|----------------------------|
//   | 收集位置   | 只在叶子（走完才完整）      | 每个节点（前缀即子集）     |
//   | 分支次数   | 恒定 2 次                   | n-start 次（for 循环）     |
//   | 去重方式   | 靠 prevSkipped（决策历史）  | 靠 i>start 树层判断        |
//
//   第三行最有意思：多叉树里"同一层的孩子"显式存在（for 循环里排队），
//   所以能直接跳过同层重复；二叉树没有"层内兄弟"概念（选/不选是正交方向），
//   去重只能去决策历史里找信息——p0090 两种去重手法差异是树形的必然结果。
//
// 面试选型法：遇到回溯题先问一句"决策树长什么样？"
//   每个元素独立"选/不选"     → 满二叉树 → 模板 B（子集、分割问题）
//   每步"从候选集挑下一个"    → 多叉树   → 模板 A（组合、排列、
//                                          p0079 网格四方向 = 4 叉树）
//   树上有约束（和/匹配）     → 挂剪枝，两种树都能挂
//
// p0090 V0 的混用 bug 用此视角诊断就是一句话：
//   "你想的是二叉树，写的是多叉树的壳"——树形想清楚一种，骨架就不会杂交。
// ──────────────────────────────────────────────────────────

// ──────────────────────────────────────────────────────────
// 【最终收束：四步法——先定树形，再往下走】
//
// 先定树形，再写代码——这是回溯题的分水岭：
// 树形定了，骨架就定了；骨架对了，剩下的只是往上面挂配件。
//
// 第一步：画树（树形 → 骨架的推导链）
//
//   问：决策树长什么样？
//       │
//       ├─ 每个元素独立"选/不选"（二叉）
//       │     → 骨架：两次递归 helper(index+1)、无 for、叶子收集
//       │     → 例：p0078/p0090 子集
//       │
//       └─ 每步"从候选集挑下一个"（多叉）
//             → 骨架：for 循环 + helper(i+1)、进入即收集（子集）
//               或选满收集（组合）
//             → 例：p0216 组合、p0046 排列、p0079 网格（4 叉）
//
//   骨架 = 递归推进方式 + 循环结构 + 收集位置，全部由树形直接决定。
//   p0090 V0 的教训反过来印证：没先定树形，两套骨架杂交，怎么修细节都是错的。
//
// 第二步之后：在骨架上按序挂三个配件（顺序也重要）
//
//   | 顺序 | 问题             | 配件               | 踩过的坑                       |
//   |------|------------------|--------------------|--------------------------------|
//   | ①    | 解在哪些节点？   | 收集位置 + 拷贝    | p0216 BUG A（剪枝挡收集）、    |
//   |      |                  |                    | BUG C（没拷贝）                |
//   | ②    | 哪些分支必死？   | 剪枝               | 收集在前、剪枝在后——          |
//   |      |                  | (break/准入/return)| 正解路径代入验证               |
//   | ③    | 哪些分支重复？   | 去重               | p0090（路径末尾 ≠ 决策历史）   |
//   |      |                  | (树层跳过/断链检测)|                                |
//
//   配件挂在骨架上，但不能反客为主——剪枝抢在收集前面，
//   就是把配件装错了位置（p0216 的判断顺序规律）。
//
// 这个思维顺序的普适性（不止回溯，所有递归题通用）：
//   树题：p0102 层序 = 按层组织的树 → 队列；p0236 LCA = 自底向上聚合 → 后序分治
//   回溯：先画决策树 → 选模板
//   DP：决策树 + 记忆化（同一棵树，不重复走相同子问题）——p0062 已预演
//
// 一句话总结这套方法论：
//   画树 → 定骨架 → 挂配件（收集→剪枝→去重）→ 拿正解路径走一遍验证。
//   从"写一步看一步"到"先想结构再动笔"——刷题从量变到质变的标志。
// ──────────────────────────────────────────────────────────

// ──────────────────────────────────────────────────────────
// 【LeetCode 解法对比】
//
// | 解法                        | 时间      | 空间   | 面试期望      |
// |-----------------------------|-----------|--------|---------------|
// | 二叉决策（V0）               | O(n·2^n)  | O(n)   | ✅ 标准答案   |
// | start 推进（V1 标准答案）    | O(n·2^n)  | O(n)   | ✅ 面试首选   |
// | 位运算（V2）                 | O(n·2^n)  | O(1)   | ⚠️ 加分备手   |
//
// 【核心易错点】
// 1. 收集必须拷贝——本题 V0 已做对（append([]int{}, cur...)）
// 2. "不可变 append 替代撤销"能用但推理链长（cap 复用细节）——显式撤销更稳
// 3. 模板 A 记得"进入即收集"（每个节点都是子集）；模板 B 在叶子收集
// 4. 位枚举只适合无重复幂集
//
// 【面试讲解建议】
// 1. 先说模型："每个元素选/不选 → 2^n 个子集 → 二叉决策树或位枚举"
// 2. 写回溯版（任一模板），强调拷贝收集
// 3. 主动提位运算："n 位 mask 枚举所有组合"——展示另一种视角
// 4. 复杂度：时间 O(n·2^n)（2^n 个子集 × 每个拷贝 O(n)）
// ──────────────────────────────────────────────────────────

func main() {
	fmt.Println(subsets([]int{1, 2, 3})) // 8 个子集（决策序）
	fmt.Println(subsets([]int{0}))       // [[] [0]]

	// V1/V2 与 V0 结果一致（顺序不同，题目允许任意顺序）
	fmt.Println(subsetsV1([]int{1, 2, 3})) // [[] [1] [1 2] [1 2 3] [1 3] [2] [2 3] [3]]（字典序）
	fmt.Println(subsetsV2([]int{1, 2, 3})) // 8 个（mask 数值序）
	fmt.Println(subsetsV1([]int{5}))       // [[] [5]]
}
