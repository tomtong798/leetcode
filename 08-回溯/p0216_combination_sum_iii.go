// LeetCode 第216题 - 组合总和 III (Combination Sum III)
//
// 【难度】中等 | 【面试频率】★★★ | 【标签】数组、回溯
//
// 【题目描述】
// 找出所有相加之和为 n 的 k 个数的组合，且满足下列条件：
//   - 只使用数字 1 到 9
//   - 每个数字最多使用一次
//
// 返回所有可能的有效组合列表。该列表不能包含相同的组合两次，组合可以以任何顺序返回。
//
// 【示例 1】
// 输入: k = 3, n = 7
// 输出: [[1,2,4]]
//
// 【示例 2】
// 输入: k = 3, n = 9
// 输出: [[1,2,6],[1,3,5],[2,3,4]]
//
// 【示例 3】
// 输入: k = 4, n = 1
// 输出: []
//
// 【数据范围】
// 2 <= k <= 9
// 1 <= n <= 60
//
// 【思路提示】回溯 1~9，剩余和/剩余个数双约束剪枝。
//
// 题目链接：https://leetcode.cn/problems/combination-sum-iii/
package main

import "fmt"

// combinationSum3 返回 1-9 中 k 个数和为 n 的所有组合。
func combinationSum3(k int, n int) [][]int {
	// 组合问题，从一个数组中依次选择三个数，三个数的和是目标值
	//
	// 🟡 注释写死了"三个数"，且实现也写死了 k=3（三层循环）——k 是参数！

	var result [][]int

	for m := 1; m <= 9; m++ { // 🔴 BUG：k 被硬编码成 3——k=2 或 k=4..9 时全错
		if m >= n { // ✅ 剪枝意图对：当前和已 >= n 再加只会超（但 m==n 且 k==1 的边界被误杀，
			break //    好在题目 k>=2，不影响本题判题）
		}
		for p := m + 1; p <= 9; p++ { // ✅ p 从 m+1 开始：保证升序 → 组合不重复（去重的关键，做对了）
			if m+p >= n {
				break
			}
			for q := p + 1; q <= 9; q++ {
				if m+p+q == n {
					result = append(result, []int{m, p, q})
				}
			}
		}
	}

	return result
}

// 【V0 点评】
// 编译通过，k=3 时结果全对（含去重），但 k≠3 全错：
//   🔴 核心 BUG：k 被硬编码成三层循环——参数 k 完全没用到！
//      k=2, n=5 应输出 [[1,4],[2,3]]，实际输出 []（三重循环找两个数的组合）
//      k=4..9 同理全错；main 的 3 个用例恰好都是 k=3/k=4，k=4,n=1 那个"碰巧"
//      输出 []（期望也是 []）——掩盖了问题
//   ✅ 去重手法正确：内层起点 = 外层变量 +1（m<p<q 严格升序），组合天然不重复
//      ——这正是回溯模板里 start+1 的展开形式，说明你理解组合去重的本质
//   ✅ 剪枝方向正确：前缀和 >= n 提前 break（数字全正数，加下去只会更大）
//   ✅ 1~9 每个数字最多用一次：升序起点保证了
//   🟡 注释"三个数"应写"k 个数"
//   🟡 循环展开只适用于固定层数——k 是变量就必须用递归（回溯）
//   本质：你手写了"递归树深度为 3"的特例。把三层循环"卷"回一层递归就是回溯——见 V1

// combinationSum3V1 【LeetCode 标准答案】回溯 + 双约束剪枝，时间 O(C(9,k))，空间 O(k)
func combinationSum3V1(k int, n int) [][]int {
	var result [][]int
	path := make([]int, 0, k)

	// start：本层从哪个数字开始选（升序去重）；remain：还差多少和；cnt：还差几个数
	var backtrack func(start, remain, cnt int)
	backtrack = func(start, remain, cnt int) {
		// 终止：恰好选满 k 个数且和刚好用完
		if cnt == 0 {
			if remain == 0 {
				result = append(result, append([]int{}, path...)) // ✅ 拷贝 path（回溯题必做）
			}
			return
		}

		for i := start; i <= 9; i++ {
			// 剪枝 1：i 已超过剩余和——后面的数更大，全剪
			if i > remain {
				break
			}
			// 剪枝 2（可选优化）：剩余 cnt 个数即使全取最大值也不够 remain，剪
			// 剩余可选 [i..9] 共 10-i 个数，若 10-i < cnt，凑不满 k 个，剪
			if 10-i < cnt {
				break
			}
			path = append(path, i)          // 做选择
			backtrack(i+1, remain-i, cnt-1) // 递归：起点 i+1（不重复用），双约束同步收紧
			path = path[:len(path)-1]       // 撤销选择（回溯）
		}
	}

	backtrack(1, n, k)
	return result
}

// 【V1 点评 - LeetCode 标准答案】
// ✅ 回溯三件套齐全：做选择 → 递归 → 撤销选择（path 弹出）
// ✅ k 参数化：递归深度由 cnt 控制——任意 k 都正确，修复 V0 的硬编码
// ✅ start 参数升序去重：i+1 下传 = 你 V0 里"p 从 m+1 开始"的通用化
// ✅ 双约束剪枝：
//    剪枝 1：i > remain 提前 break（= 你 V0 的前缀和剪枝）
//    剪枝 2：剩余数字个数 10-i < cnt 时凑不满 k 个，剪（V0 没有的优化）
// ✅ 收集时 append([]int{}, path...)：拷贝快照——path 会被后续回溯复用，直接存引用会翻车
//    （这是回溯收集的固定坑，与 p0017 电话号码的 result = append(result, curS) 同理）
// 时间 O(C(9,k))（组合数上界，剪枝后远小于此），空间 O(k) 递归栈
// 追踪 k=3, n=7：1 → 2 → 4（1+2+4=7 ✓）；1 → 3 → 剩 3 但需 >3 ✗...
//   输出 [[1,2,4]] ✅

// ──────────────────────────────────────────────────────────
// 【V0 的三层循环 ↔ V1 的递归：同一个搜索树的两种写法】
//
// 你的三层循环其实就是"深度为 3 的搜索树"的手工展开：
//
//   for m := 1..9            ← 第 1 层选 m
//     for p := m+1..9        ← 第 2 层选 p（起点 = 上一层 +1）
//       for q := p+1..9      ← 第 3 层选 q
//         if 和 == n: 收集
//
// 回溯把三层"卷"成一层递归：
//
//   backtrack(start, ...) {
//     if 选满 k 个 { 判和; return }
//     for i := start..9 {     ← 循环变量 = 这一层的 m/p/q
//       选 i → 递归(i+1) → 撤销
//     }
//   }
//
// 对应关系：
//   三层循环的变量 (m,p,q)  →  递归栈上的 path
//   "p 从 m+1 开始"          →  start 参数每层 +1
//   循环嵌套深度 3          →  cnt 递减到 0 终止
//   前缀和 >= n break       →  i > remain break
//
// 当 k 固定且很小时，循环展开完全可行（甚至更快）；k 是变量就必须递归。
// 这也解释了回溯的本质：【用递归栈代替手写嵌套循环】，层数动态可变。
// ──────────────────────────────────────────────────────────

// ──────────────────────────────────────────────────────────
// 【LeetCode 解法对比】
//
// | 解法                       | 时间        | 空间   | 面试期望      |
// |----------------------------|-------------|--------|---------------|
// | 三层循环硬编码（V0 有 bug） | O(C(9,3))   | O(1)   | ❌ k≠3 全错  |
// | 回溯+双剪枝（V1 标准答案）  | O(C(9,k))   | O(k)   | ✅ 面试首选   |
// | 位运算枚举 9 位子集         | O(2^9)      | O(1)   | ⚠️ 可以       |
//
// 【核心易错点】
// 1. k 是参数不是常量——循环展开写死层数就废了，必须递归
// 2. 去重靠"起点递增"：下一层从 i+1 开始选（组合，不是排列）
// 3. 收集必须拷贝 path：append([]int{}, path...)——path 会被复用
// 4. 剪枝两个方向：数字太大（i > remain）凑过头；数字太少（10-i < cnt）凑不满
// 5. 终止判断：cnt==0 时看 remain 是否恰好为 0（和与个数双条件）
//
// 【面试讲解建议】
// 1. 先说框架："回溯 = 递归版的可变层数循环，path 记路径，start 保升序"
// 2. 讲剪枝："两个方向——加过头剪、凑不满也剪"
// 3. 提拷贝坑："收集时必须快照 path"
// 4. 复杂度：O(C(9,k)) 组合数上界，剪枝后远小于
// ──────────────────────────────────────────────────────────

func main() {
	fmt.Println(combinationSum3(3, 7)) // [[1 2 4]]  ✅ k=3 V0 碰巧对
	fmt.Println(combinationSum3(3, 9)) // [[1 2 6] [1 3 5] [2 3 4]] ✅
	fmt.Println(combinationSum3(4, 1)) // [] ✅（期望恰好也是 []，掩盖了 bug）

	// V0 的反例：k≠3 全错
	fmt.Println(combinationSum3(2, 5))   // [] ❌ 应为 [[1 4] [2 3]]
	fmt.Println(combinationSum3V1(2, 5)) // [[1 4] [2 3]] ✅

	// V1 全 k 正确
	fmt.Println(combinationSum3V1(3, 7))  // [[1 2 4]]
	fmt.Println(combinationSum3V1(3, 9))  // [[1 2 6] [1 3 5] [2 3 4]]
	fmt.Println(combinationSum3V1(4, 1))  // []
	fmt.Println(combinationSum3V1(9, 45)) // [[1 2 3 4 5 6 7 8 9]] 全选

	// V2（combinationSum3_1）：任何输入都返回空（BUG A 剪枝挡住收集）
	fmt.Println(combinationSum3_1(3, 7)) // [] ❌ 应为 [[1 2 4]]

	// V2-fix（combinationSum3_2）：修复后与 V1 结果一致
	fmt.Println(combinationSum3_2(3, 7))  // [[1 2 4]]
	fmt.Println(combinationSum3_2(3, 9))  // [[1 2 6] [1 3 5] [2 3 4]]
	fmt.Println(combinationSum3_2(2, 5))  // [[1 4] [2 3]]
	fmt.Println(combinationSum3_2(9, 45)) // [[1 2 3 4 5 6 7 8 9]]
}

// combinationSum3_1 用户第二版：递归回溯（结构已对，细节三处 bug）。
func combinationSum3_1(k int, n int) [][]int {
	var result [][]int

	var helper func(start int, curSum int, cur []int)
	helper = func(start int, curSum int, cur []int) {
		if start >= n { // 🟡 语义混杂：start 是"候选数字"，拿它和 n（和）比较——
			return //    只在 k≥2 时碰巧无害（单个数 ≥ n 时确实凑不出）
		}

		if curSum+start > n { // 🔴 BUG A（致命，见点评）：剪枝放在收集判断【之前】，
			return //    且 curSum==n 时 curSum+start = n+start > n 恒成立（start≥1）
		} //    → 收集分支永远执行不到，result 恒为空！

		if len(cur) == k && curSum == n { // 🔴 死代码：永远到不了（被 BUG A 挡住）
			result = append(result, cur) // 🔴 BUG C：直接 append cur 没拷贝——
			return //    slice 引用共享，后续回溯复用同一底层数组会篡改已收集的结果
		}

		for i := start; i <= 9; i++ {
			cur = append(cur, i)
			helper(start+1, curSum+i, cur) // 🔴 BUG B：应该传 i+1 不是 start+1！
			cur = cur[:len(cur)-1] //    i>start 时下一层可重选 [start+1..i] 的数
		} //    → 数字重复使用（如 [1,3,3]），违反"每个数最多一次"
	}

	return result
}

// 【V2 点评 - combinationSum3_1】
// 结构进步巨大（对照 V1 学到了回溯三件套 + start 参数 + curSum 下传），但三个 bug：
//
//   🔴 BUG A（致命·最隐蔽）：剪枝顺序杀死收集分支
//      收集需要 curSum == n；而收集判断前有 curSum+start > n 的剪枝——
//      curSum==n 时 curSum+start = n+start ≥ n+1 > n 恒成立（start ≥ 1 永远为真）
//      → 收集分支是【死代码】，任何输入都返回空！
//      追踪 k=3, n=7 的正解 [1,2,4]：
//        helper(3,3,[1,2]) 选 i=4 → helper(4, 7, [1,2,4])
//        → start=4 < 7 ✓；curSum+start = 7+4 = 11 > 7 → return（收集判断没执行到）
//      修复：收集判断必须放在剪枝【之前】，或把剪枝移进循环里对候选 i 判断
//
//   🔴 BUG B：helper(start+1) 应为 helper(i+1)
//      循环里 i 从 start 走到 9，但递归永远传 start+1：
//        i == start 时碰巧对；i > start 时下一层起点 ≤ i，可重选 ≤i 的数
//      → 同一数字被用两次（[1,3,3] 这类非法组合），也违背去重
//      V0 你手写循环时"p 从 m+1 开始"是对的——递归版里这个 +1 换成了 start+1 就错了
//
//   🔴 BUG C：result = append(result, cur) 没拷贝
//      cur 的底层数组会被回溯复用（弹出再压入），收集时存的是引用——
//      后续修改会篡改之前的结果。必须 append([]int{}, cur...)
//
//   ✅ 值得肯定：回溯三件套（append → 递归 → 弹出）结构完整；
//      curSum 作为参数下传（自顶向下传状态，符合 p0226 的范式分类）
//   🟡 len(cur)==k && curSum==n 应该在 len==k 时就 return（无论和是否相等）——
//      否则 len 超过 k 后还在白白递归
//
// 三个 bug 一并修复 → combinationSum3_2（其实就是 V1 的骨架 + 你的变量命名）

// combinationSum3_2 修复版：保持你的参数风格，修 A/B/C 三处
func combinationSum3_2(k int, n int) [][]int {
	var result [][]int

	var helper func(start int, curSum int, cur []int)
	helper = func(start int, curSum int, cur []int) {
		// ✅ 修复 A：收集判断放最前（选满 k 个就结算，无论成败都要 return）
		if len(cur) == k {
			if curSum == n {
				result = append(result, append([]int{}, cur...)) // ✅ 修复 C：拷贝快照
			}
			return
		}

		for i := start; i <= 9; i++ {
			// ✅ 修复 A（剪枝移到循环内，对候选 i 判断——语义正确且等价于入口剪枝）
			if curSum+i > n {
				break // 数字递增，后面只会更超
			}
			cur = append(cur, i)
			helper(i+1, curSum+i, cur) // ✅ 修复 B：i+1 保证每个数只用一次
			cur = cur[:len(cur)-1]
		}
	}

	helper(1, 0, []int{})
	return result
}

// 【V2-fix 点评 - combinationSum3_2】
// ✅ 三处修复后与 V1 逻辑等价（V1 用 remain 倒数，这里用 curSum 正数——同一信息两种记法）
// ✅ 剪枝 break 放循环内：对"候选 i"判断而不是对"入口状态"判断，从根上避免挡住收集
// ✅ 删掉了 start>=n 剪枝：对候选 i 的判断已覆盖它，少一个语义混杂的条件
// 你的原始递归骨架没问题——错的只是"顺序"和"+1 的对象"，这类细节 bug
// 正是回溯题最容易踩的，靠反例追踪（如 [1,2,4] 的路径）来抓

// ──────────────────────────────────────────────────────────
// 【收集和剪枝的位置怎么确定？——判断顺序规律】
//
// 核心规律一句话：按"误伤可能性"排序——越容易误伤合法状态的判断，越要放后面
// （或收窄适用范围）；绝不误伤的判断放前面收口。
//
// 判断法：问一句"终止状态会被它挡住吗？"
//   收集判断（终止状态）：len(path)==k / target==0 —— 合法终点，必须被执行到
//   剪枝判断（提前退出）：和超了 / 数不够了 —— 只剪非法分支，不该碰到合法终点
//
// 标准模板（顺序不能乱）：
//
//   func backtrack(...) {
//     ① 收集判断   ← 最先：合法终点必须先落地，任何剪枝都不能抢在它前面
//     ② 硬终止     ← 候选耗尽 / 越界 → return
//     ③ 剪枝判断   ← 其次：只剪"继续走下去必然失败"的分支
//     ④ for 循环   ← 做选择 → 递归 → 撤销
//   }
//
// 为什么收集必须在剪枝前——combinationSum3_1 的 BUG A 就是反例：
//
//   if curSum+start > n { return }              // 剪枝放前面
//   if len(cur) == k && curSum == n { 收集 }     // 永远死代码！
//
//   逻辑矛盾：收集要求 curSum == n，而那一刻剪枝条件 curSum+start > n
//   恒真（n+start > n）——剪枝只想杀非法分支，却把唯一的合法终点也"剪"掉了。
//
// 两种修复思路（同一规律的两面）：
//   思路 1 调顺序：收集判断放函数第一行
//   思路 2 收窄对象：剪枝移进循环内，对"将要选的 i"判断——
//        for i := start; i <= 9; i++ {
//            if curSum + i > n { break }  // 剪的是"选 i 这一步"，不碰已达终点的状态
//        }
//   思路 2 更本质：剪枝剪的是【分支】，不是【状态】——
//   对候选 i 做判断，天然不会误伤已经合法的入口状态。
//
// 写过的题对照验证：
//
//   | 题        | ① 收集                 | ③ 剪枝                        | 位置关系 |
//   |-----------|------------------------|-------------------------------|----------|
//   | p0216 V1  | cnt==0 → 判 remain     | i>remain、10-i<cnt（循环内）  | ✅       |
//   | p0022 括号 | len(cur)==2n           | left<n、right<left（准入式）  | ✅       |
//   | p0017 电话 | index==len             | 无约束不剪                    | ✅       |
//
// p0022 的精妙之处：剪枝写成 if left < n { 才能选 '(' } ——
// 从"禁止进入"改成"允许才进入"，判断和动作绑在一起，顺序问题从根上消失。
//
// 三条实操规则：
//   1. 收集判断永远放函数第一行——它是合法终点，任何提前 return 都不该抢在它前面
//   2. 剪枝尽量放进循环内、对"候选 i"判断——剪的是分支不是状态，
//      break 还能利用有序性批量剪
//   3. 入口剪枝只在"当前状态继续必然失败"时用，且要验证一个特例：
//      拿着【正解路径的终点状态】代入剪枝条件，看会不会被误杀——
//      这就是抓 BUG A 的方法（拿 [1,2,4] 终点 curSum=7 代入 curSum+start>n，立刻暴露）
//
// 一句话：收集是终点、剪枝是路障——路障只能放在"通往非法分支"的路上，
// 放到终点门口就把答案也拦住了。验证办法：永远拿一条已知正解路径走一遍判断顺序。
// ──────────────────────────────────────────────────────────

// ──────────────────────────────────────────────────────────
// 【回溯系列总纲：本质、解决的问题、与枚举/DP 的关系】
//
// ── 一、回溯是什么：三层理解 ──
//
// 理解 1（结构层）：回溯 = 层数不确定的多层 for 循环嵌套，递归化
//   每层 for 逻辑同构 → 可以写成一层递归；层数由参数控制（k、remain、len(path)...）
//   对应关系：循环变量序列 (m,p,q) → 递归栈上的 path；嵌套深度 → 递归深度
//
// 理解 2（机制层）：递归下行、循环横行、return 后还原
//   做选择（递归前，自上而下）→ 递归探索分支 → 撤销选择（递归后，回来还原）
//   撤销选择是【灵魂】——path 是共享的，不恢复现场，残留会污染后续分支：
//     cur = append(cur, i)          // ① 做选择
//     helper(i+1, curSum+i, cur)    // ② 递归
//     cur = cur[:len(cur)-1]        // ③ 撤销（恢复现场）★ 不可省略
//   例外：Go 字符串不可变 + 传值时（p0017 的 curS + c 每次新对象）天然免撤销——
//   换 []byte 就必须显式撤销，别依赖这种运气
//
// 理解 3（本质层）：回溯就是枚举——但不是"傻枚举"，是"聪明的枚举"
//   暴力枚举：先生成所有完整解，再逐个检查
//   回溯枚举：边生成边检查，走一步看一步，死路立刻掉头（backtracking = 往回走）
//   = 枚举解空间树的 DFS + 三个优化装置（见下）
//
// ── 二、三个优化装置（把暴力枚举的浪费挤干）──
//
//   1. 提前剪枝：剪的是【子树】不是单个解
//      p0216：curSum=3 时选 i=5 → 8>7 → break，[1,2,6]...[1,2,9] 全不用看
//   2. 剪重复结构：同一批解不生成两次
//      组合 [1,2] 与 [2,1] 等价 → start 递增只生成升序那个
//      （9 选 3：排列 504 个 vs 组合 84 个，省 6 倍）
//   3. 撤销复用：一条 path 走完所有分支
//      暴力存所有候选 O(解空间) 内存 → 回溯 O(k) 内存
//
//   剪枝的三种形态（都用过）：
//     break 退出循环   p0216 的 curSum+i > n（利用有序性批量剪）
//     准入式判断       p0022 的 if left < n { 才能选 '(' }（禁止→允许，从根上无顺序问题）
//     入口 return      p0110 的 -1 哨兵（整棵子树不再探索）
//
// ── 三、回溯解决的问题全景 ──
//
//   共同特征：解 = 一系列选择；要求"所有解"而非"最优解"
//
//   | 类型          | 特征               | 本目录实例            | 去重手法    |
//   |---------------|--------------------|-----------------------|-------------|
//   | 组合          | 选 k 个，无序      | p0039 p0040 p0216    | start 递增  |
//   | 子集          | 每个元素选/不选    | p0078 p0090          | start 递增  |
//   | 排列          | 有序               | p0046 p0047          | used 数组   |
//   | 棋盘          | 网格上放/走        | p0051 p0079          | 位置约束    |
//   | 括号/路径生成 | 边构造边检查       | p0017 p0022          | 准入式剪枝  |
//
// ── 四、回溯 vs DP 的分界（同一个"选/不选"的递归结构）──
//
//   回溯：每个叶子都要去（列所有解）——解的数量可控时用
//   DP：子问题答案记下来复用（重叠子问题只算一次）——计数/最优值时用
//   亲历案例：p0062 不同路径——求路径【总数】（天文数字），回溯数不完，DP 一步算出
//   解空间指数爆炸时（如 20! 排列），回溯剪枝只能减小常数，最坏仍指数
//
// ── 五、一句话总结 ──
//
//   回溯 = 把"逐个做选择"组织成解空间树：递归下行（做选择）、循环横行（换选择）、
//   return 后还原（撤销）；剪枝在树长大之前砍掉注定失败的子树。
//   它是解空间树上的一次深度优先漫步——枚举的是同一棵树，走法聪明得多。
// ──────────────────────────────────────────────────────────
